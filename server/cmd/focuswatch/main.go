// Команда focuswatch — помощник активного окна.
//
// Крошечный процесс: раз в несколько секунд спрашивает у Windows, какое окно
// сейчас в фокусе (имя процесса + заголовок), и печатает в stdout одну JSON-строку,
// когда фокус сменился. Отдельным процессом — чтобы запрос к системному API не
// мешал ни серверу (у сервера свои дела и модель), ни персонажу (у него кадры).
//
// Смерть родителя помощник замечает по закрытию stdin: Electron закрылся —
// помощник вышел сам, «сирот» в системе не остаётся.
//
// Запуск (обычно его делает оболочка, не человек):
//
//	focuswatch.exe -interval 4s
//
// На не-Windows помощник не работает: печатает одну строку с объяснением и
// выходит — сборка проекта на любой системе остаётся зелёной.
package main

import (
	"flag"
	"os"
	"time"
)

func main() {
	interval := flag.Duration("interval", 4*time.Second, "как часто спрашивать активное окно")
	selftest := flag.Bool("selftest", false, "окно для самопроверки (только окно самопроверки)")
	flag.Parse()
	if *interval < time.Second {
		*interval = time.Second // чаще секунды спрашивать незачем, CPU дороже пользы
	}
	selftestMode = *selftest
	os.Exit(collect(*interval))
}
