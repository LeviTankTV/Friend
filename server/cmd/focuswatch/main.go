// Команда focuswatch — помощник активного окна.
//
// Крошечный процесс: раз в несколько секунд спрашивает у Windows, какое окно
// сейчас в фокусе (имя процесса + заголовок), и печатает в stdout одну JSON-строку,
// когда фокус сменился. Отдельным процессом — чтобы запрос к системному API не
// мешал ни серверу (у сервера свои дела и модель), ни персонажу (у него кадры).
//
// Смерть родителя помощник замечает по закрытию stdin: Electron закрылся —
// помощник вышел сам, «сирот» в системе не остаётся.
//
// Запуск (обычно его делает оболочка, не человек):
//
//	focuswatch.exe -interval 4s
//
// На Windows и Linux помощник читает активное окно (user32 / X11), на macOS
// и прочих ОСях печатает одну строку с объяснением и выходит — сборка проекта
// на любой системе остаётся зелёной.
package main

import (
	"flag"
	"os"
	"time"
)

// selftestMode — режим самопроверки оболочки. В нём помощник выдаёт ОКНО
// ТЕСТА: заголовок начинается с маркера SELFTEST- — по нему оболочка
// подставляет фиксированные границы (своё окно самопроверки), а сервер такие
// строки не принимает вовсе (см. internal/server handleFocus). Живое окно в
// этом режиме не сообщается: прогон не должен трогать контекст рабочей Миры.
// Живёт здесь, в общем файле: его читает main, а объявлять в каждом
// платформенном файле нельзя — сборка третьей ОСи осталась бы без переменной.
var selftestMode = false

// constSelftestTitle — префикс заголовка тестового окна.
const constSelftestTitle = "SELFTEST-окно-посадки"

// HEARTBEAT — с какой периодичностью печатать строку, даже когда окно не
// менялось: по ней сервер узнаёт, что человек «исчез» (idle растёт), не
// дожидаясь смены окна.
const HEARTBEAT = 30 * time.Second

// sample — строка помощника: имя процесса, заголовок, idle и геометрия
// окна. Одна на все платформы (поля — общий контракт с оболочкой и
// сервером), платформенные файлы только заполняют её.
type sample struct {
	Process string `json:"process"`
	Title   string `json:"title"`
	// Idle — секунд с последнего движения мышью/клавиатурой. 0 означает
	// «данных нет» (замер не удалось), сервер в этом случае не считает idle.
	Idle int `json:"idle,omitempty"`
	// Bounds — прямоугольник окна на экране: x, y, ширина, высота. Это
	// ГЕОМЕТРИЯ, а не содержимое: промпт модели окно не получает (там
	// остаются только процесс и заголовок), Bounds идёт по одному каналу на
	// страницу — по ней персонаж садится на верх чужого окна (посадка «на
	// окне»). Пустой прямоугольник = «геометрии нет» (на macOS — всегда:
	// границы чужих окон требует Accessibility-разрешения).
	Bounds [4]int `json:"bounds,omitempty"`
}

func main() {
	interval := flag.Duration("interval", 4*time.Second, "как часто спрашивать активное окно")
	selftest := flag.Bool("selftest", false, "окно для самопроверки (только окно самопроверки)")
	flag.Parse()
	if *interval < time.Second {
		*interval = time.Second // чаще секунды спрашивать незачем, CPU дороже пользы
	}
	selftestMode = *selftest
	os.Exit(collect(*interval))
}
