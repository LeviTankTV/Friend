package moodread

import "testing"

// Таблица кейсов (этап 9в): что детектор обязан услышать, а что — промолчать.
func TestRead(t *testing.T) {
	cases := []struct {
		text string
		want string
	}{
		{"Я сегодня ужасно устал", Tired},
		{"устал, сил нет", Tired},
		{"не выспалась совсем", Tired},
		{"мне грустно", Sad},
		{"всё надоело...", Sad},
		{"опять всё развалилось", Sad},
		{"Наконец-то сделал! Ура!", Happy},
		{"спасибо, класс!", Happy},
		{"меня это бесит!!!", Angry},
		{"он меня достал", Angry},
		{"тревожно немного", Anxious},
		{"боюсь, что не успею", Anxious},
		{"ок", ""},
		{"посмотри файл README.md", ""},
		{"", ""},
		{"   ", ""},
	}
	for _, c := range cases {
		if got := Read(c.text); got != c.want {
			t.Fatalf("«%s»: получили «%s», ждали «%s»", c.text, got, c.want)
		}
	}
}

// Многоточие усиливает грусть, «!» — силу радости/злости/тревоги; нейтральная
// реплика не получает ярлыка даже с punctuation-шумом.
func TestPunctuation(t *testing.T) {
	if Read("мне грустно...") != Sad {
		t.Fatal("многоточие не усиливает грусть")
	}
	if Read("ок...") != "" {
		t.Fatal("многоточие не должно придумывать настроение на пустом месте")
	}
	if Read("ура!") != Happy {
		t.Fatal("восклицание не усиливает радость")
	}
}
