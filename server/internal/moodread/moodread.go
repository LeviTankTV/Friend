// Package moodread читает НАСТРОЕНИЕ реплик человека (этап 9в, эмпатия).
//
// Детектор локальный и намеренно простой: список корней слов (русские и
// английские — эмпатия не должна зависеть от языка персоны) + пунктуационные
// сигналы («...» — спад, «!» — сила). Никакого анализа содержимого, ML или
// сети: из реплики наружу не уходит НИЧЕГО, кроме ОДНОГО кода состояния,
// который сервер переводит в слово промпта (internal/i18n) и кладёт в кадр
// ответа окну — аватар меняет лицо.
//
// Код не хранится в памяти и не уходит в Microsoft: это состояние текущей
// беседы, живущее до следующей реплики человека.
package moodread

import "strings"

// Коды состояния — стабильные идентификаторы: в промпт идёт слово на языке
// персоны (i18n.USTired и т.д.), в кадр окну — код, страницу не волнует язык.
const (
	Tired   = "tired"
	Sad     = "sad"
	Happy   = "happy"
	Angry   = "angry"
	Anxious = "anxious"
)

// keywords — корни слов (регистр и пунктуация не важны: сравнение по
// нормализованной строке). Слово ловится как подстрока, поэтому «устал»,
// «устала», «усталость» ловятся корнем «устал», а "tired", "tiresome" —
// корнем "tired". Оба языка в одном списке: русский человек может вставить
// английское слово, и наоборот.
var keywords = map[string][]string{
	Tired: {
		"устал", "устала", "измотан", "вымотан", "разбит", "разбита",
		"не выспал", "не выспала", "спать хочу", "охота уснуть",
		"нет сил", "сил нет", "нет энергии", "добрал ночи",
		"tired", "exhaust", "worn out", "sleepy", "no energy",
	},
	Sad: {
		"грустн", "печальн", "тоскливо", "обидно", "обидел", "расстро",
		"плохо", "плохая", "паршиво", "уныло", "депресс", "никак",
		"нет настроения", "бессмысленно", "бесполезно", "надоело",
		"опять всё", "всё надоело",
		"sad", "upset", "down", "blue", "depress", "lone", "hurt",
	},
	Happy: {
		"рад", "рада", "счастл", "класс", "отлично", "здорово", "ура",
		"наконец-то", "наконец то", "круто", "супер", "отдыхаю",
		"получилось", "вышло", "спасибо", "благодарю",
		"happy", "glad", "great", "awesome", "nice", "finally", "thanks",
	},
	Angry: {
		"бесит", "бесят", "злюсь", "злость", "раздража", "достал",
		"достала", "достали", "ненавиж", "бешит", "надоед", "надрал",
		"надоел", "выносит мозг",
		"angry", "mad", "furious", "annoy", "hate", "pissed",
	},
	Anxious: {
		"тревог", "тревож", "страшно", "боюсь", "пережива", "волну",
		"беспоко", "паник", "нервнич", "напряж", "не по себе", "неловко",
		"anxious", "anxiety", "scared", "afraid", "worry", "worried", "nervous", "panic",
	},
}

// Read определяет настроение реплики. "" — нейтрально: сигнал не прозвучал
// (и не должен попадать в промпт). Побеждает ярлык с наибольшим весом;
// пунктуация усиливает: «...» — спад (грусть/тревога), «!» — сила
// (радость/злость/тревога).
func Read(text string) string {
	s := strings.ToLower(strings.TrimSpace(text))
	if s == "" {
		return ""
	}
	bangs := strings.Count(s, "!")
	if bangs > 3 {
		bangs = 3
	}
	dots := strings.Count(s, "...")

	type score struct {
		n     int
		label string
	}
	best := ""
	bestN := 0
	for label, list := range keywords {
		n := 0
		for _, w := range list {
			if strings.Contains(s, w) {
				n++
			}
		}
		if n == 0 {
			continue
		}
		// Точка с восклицанием — сила; многоточие — тихий спад.
		switch label {
		case Happy:
			n += bangs
		case Angry:
			n += bangs
		case Anxious:
			n += bangs + dots
		case Sad:
			n += dots
		}
		// При равных весах предпочитаем в порядке: грусть, злость,
		// усталость, тревога, радость — сочувствие важнее веселья.
		if n > bestN || (n == bestN && priority(label) < priority(best)) {
			bestN, best = n, label
		}
	}
	return best
}

func priority(label string) int {
	switch label {
	case Sad:
		return 0
	case Angry:
		return 1
	case Tired:
		return 2
	case Anxious:
		return 3
	case Happy:
		return 4
	}
	return 5
}
