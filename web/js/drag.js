// drag.js — перетаскивание персонажа мышью.
//
// Перетаскивается ОКНО (в оболочке) или сам аватар в странице (в браузере) —
// разницу прячет FriendBridge. Здесь только арифметика, и в ней два решения,
// оба получены замером, а не догадкой.
//
// 1) Цель считается ОТ НАЧАЛА перетаскивания и задаётся АБСОЛЮТНО — «поставь
//    окно сюда», а не «сдвинь на столько-то». Оболочка считает дельту от
//    позиции, которую она только что прочитала у окна, а чтение может отстать
//    на пару пикселей (масштаб 125% округляет каждый шаг до 1,25 пикселя): тогда
//    движение теряется вместе с задержкой. Замерено: пять шагов по 10 давали
//    сдвиг 46×50, а длинная протяжка в 120 шагов не доезжала до курсора на 35
//    пикселей. Абсолютную цель можно повторять сколько угодно раз — результат
//    один и тот же, поэтому отставание не накапливается.
//
// 2) Все обращения к оболочке идут ОДНОЙ ОЧЕРЕДЬЮ. Оболочка отвечает на
//    каждый запрос асинхронно (это IPC), и если слать запросы «как придёт
//    событие», позиция окна приезжает в ответах вперемешку: окно дёргается, а
//    на быстрой протяжке (нажал-отпустил за миллисекунды) весь переезд вообще
//    терялся — очередь ответов не успевала начаться. В очереди порядок
//    гарантирован: следующая цель считается по настоящей позиции из прошлого
//    ответа, а сохранение позиции на сервере встаёт в ту же очередь и потому
//    не может записать устаревшее место.
//
// И третье, не про арифметику: перетаскивание начинается только на САМОМ
// персонаже (hooks.hitTest). Окно компаньона — прямоугольник шире персонажа, и
// перетаскивание «за пустое место рядом» означало бы, что этот прямоугольник
// отнимает клики у рабочего стола.
window.FriendDrag = (function () {
  'use strict';

  function attach(target, bridge, hooks) {
    const h = hooks || {};
    let dragging = false;
    let last = null;      // последние экранные координаты курсора
    let moved = 0;        // накопитель, чтобы отличить клик от перетаскивания
    let acc = { x: 0, y: 0 };   // сколько курсор прошёл с момента нажатия
    let sent = { x: 0, y: 0 };  // сколько из этого уже попросили у оболочки
    let origin = null;    // позиция окна в момент нажатия
    let want = null;      // последняя ЗАПРОШЕННАЯ абсолютная цель
    let chain = Promise.resolve();

    // enqueue — все операции с окном строго по очереди (см. пункт 2 выше).
    function enqueue(task) {
      chain = chain
        .then(task)
        .catch((err) => { console.error('перетаскивание: оболочка не справилась —', err); });
      return chain;
    }

    // screenX/screenY — единственные координаты, которые не зависят от
    // положения окна; при перетаскивании окна clientX «замирает» (окно едет
    // вместе с мышью), а screen — нет.
    function pointerXY(ev) {
      return { x: ev.screenX, y: ev.screenY };
    }

    // pull двигает окно к абсолютной цели: где должно стоять окно, если её
    // утащили от точки нажатия на acc пикселей. Повторный запрос той же цели
    // безвреден (это и спасает от задержки чтения позиции), а если курсор успел
    // уехать, пока мы ждали ответа, — пересчитаем цель по свежему acc.
    function pull() {
      if (!origin) {
        // Первый шаг: позиция окна ещё неизвестна (ни одного ответа не было) —
        // просим чистую дельту и из ответа узнаём точку нажатия.
        const stepX = acc.x - sent.x;
        const stepY = acc.y - sent.y;
        if (Math.round(stepX) === 0 && Math.round(stepY) === 0) return false;
        const asked = { x: stepX, y: stepY };
        sent = { x: acc.x, y: acc.y };
        void enqueue(() => Promise.resolve(bridge.moveBy(asked.x, asked.y)).then((pos) => {
          // Точка отсчёта берётся из ПЕРВОГО ответа и больше не переписывается.
          //
          // Про \"первый\" здесь не для красоты: пока ответ не пришёл, следующий шаг
          // мышки тоже уходит дельтой (точка отсчёта ещё неизвестна). Если брать её
          // из каждого такого ответа, то «pos − asked» считается от уже сдвинутого
          // места и уезжает вперёд на шаг за шагом: вся протяжка смещается, окно
          // проезжает 120 вместо 100. Замерено именно так.
          if (!origin) origin = { x: pos.x - asked.x, y: pos.y - asked.y };
          if (dragging) pull();
        }));
        return true;
      }
      const wantX = Math.round(origin.x + acc.x);
      const wantY = Math.round(origin.y + acc.y);
      if (want && wantX === want.x && wantY === want.y) return false;
      want = { x: wantX, y: wantY };
      void enqueue(() => Promise.resolve(bridge.setPosition(wantX, wantY)).then(() => {
        // Если окно не доехало (упёрлось в край экрана или оболочка поправила
        // позицию) — ничего пересчитывать не нужно: следующая цель не зависит от
        // ответа, она абсолютная. Так край экрана перестаёт быть «стоком»
        // движения: увела мышь от края — она поехала за ней с того же места.
        if (dragging) pull();   // курсор мог уехать, пока мы ждали ответа
      }));
      return true;
    }

    function onDown(ev) {
      if (h.hitTest && !h.hitTest(ev.clientX, ev.clientY)) return;
      dragging = true;
      moved = 0;
      acc = { x: 0, y: 0 };
      sent = { x: 0, y: 0 };
      origin = null;
      want = null;
      last = pointerXY(ev);
      target.classList.add('dragging');
      if (h.onStart) h.onStart();
      ev.preventDefault();
      // Позицию окна здесь НЕ спрашиваем: ответ пришёл бы асинхронно и мог
      // опоздать к концу быстрой протяжки. Она узнаётся из первого же ответа
      // на переезд — см. pull().
    }

    function onMove(ev) {
      if (!dragging || !last) return;
      const p = pointerXY(ev);
      let dx = p.x - last.x;
      let dy = p.y - last.y;
      // Запасной путь: если оболочка не отдала screen-координаты (бывает в
      // некоторых сборках), берём привычные movement-поля.
      if (dx === 0 && dy === 0 && typeof ev.movementX === 'number') {
        dx = ev.movementX;
        dy = ev.movementY;
      }
      last = p;
      if (dx === 0 && dy === 0) return;
      moved += Math.abs(dx) + Math.abs(dy);
      acc.x += dx;
      acc.y += dy;
      pull();
    }

    // settle — последнее выравнивание по абсолютной цели протяжки. Шаг, который
    // оболочка сообщила в ответ, может слегка расходиться с тем, где окно
    // оказалось на самом деле (система догоняет его округлением). Если это
    // расхождение не выбрать в конце, персонаж останется на несколько пикселей
    // позади курсора — ровно то и наблюдалось: 46 вместо 50.
    function settle() {
      if (!origin) return Promise.resolve(null);
      // Последнее выравнивание по той же абсолютной цели, что у последнего шага.
      // Позицию окна для этого читать не нужно — именно чтение и было источником
      // отставания: «подвинь на (цель − прочитанное место)» уезжает на задержку
      // чтения. Повторная постановка того же места ничего не портит.
      return Promise.resolve(bridge.setPosition(Math.round(origin.x + acc.x), Math.round(origin.y + acc.y)));
    }

    function onUp() {
      if (!dragging) return;
      dragging = false;
      last = null;
      target.classList.remove('dragging');
      // Догоняем остаток и только ПОСЛЕ этого читаем позицию: иначе на сервер
      // ушло бы место, с которого перетаскивание началось.
      pull();
      void enqueue(() => settle().then(() => bridge.getPosition()).then((pos) => {
        // Сохраняем на сервере только НАСТОЯЩЕЕ перетаскивание: обычный клик
        // по персонажу — это не переезд окна и не повод писать на диск.
        if (h.onEnd) h.onEnd(pos, moved);
        // Клик (а не перетаскивание) отдаём наружу: на нём живут реакции
        // персонажа и открытие окна ввода разговора.
        if (moved < 4 && h.onClick) h.onClick();
      }));
    }

    target.addEventListener('pointerdown', onDown);
    window.addEventListener('pointermove', onMove);
    window.addEventListener('pointerup', onUp);
    window.addEventListener('blur', onUp);

    // rebase — «окно поставили не туда, куда просили»: привязка перетаскивания
    // к новому месту. Посадка «на окне» (см. main.js, seatWatch) ставит окно на
    // кромку мишени прямо посреди протяжки; без привязки следующий шаг мыши
    // вернул бы окно по старой цели, и персонаж соскочил бы с окна.
    // После rebase отсчёт снова от курсора: acc обнуляется.
    function rebase(x, y) {
      if (!dragging) return;
      origin = { x: Math.round(x), y: Math.round(y) };
      acc = { x: 0, y: 0 };
      sent = { x: 0, y: 0 };
      want = null;
    }

    return {
      isDragging: () => dragging,
      // windowPos — где окно СЕЙЧАС по нашим счётчикам (точка нажатия +
      // пройденный курсором путь), без чтения у оболочки: на неё опираться
      // посреди протяжки нельзя (ответы отстают), а для привязки к мишени
      // достаточно.
      windowPos: () => (origin && dragging
        ? { x: Math.round(origin.x + acc.x), y: Math.round(origin.y + acc.y) }
        : null),
      rebase: rebase,
      // enqueue — встать в общую очередь переездов окна (для проверок и
      // «догнать» окно после внешнего setBounds).
      enqueue: enqueue,
      // target — куда протяжка хотела поставить окно, точка — откуда она
      // отсчитывает движение. Нужны проверке оболочки: без них расхождение
      // «доехало на 45 вместо 50» не разложить на «не ту цель попросили» и
      // «цель верная, но окно не доехало».
      target: () => (want ? { x: want.x, y: want.y } : null),
      origin: () => (origin ? { x: origin.x, y: origin.y } : null),
      detach: () => {
        target.removeEventListener('pointerdown', onDown);
        window.removeEventListener('pointermove', onMove);
        window.removeEventListener('pointerup', onUp);
        window.removeEventListener('blur', onUp);
      },
    };
  }

  return { attach: attach };
})();
